// TestResolveEval pins the precedence "CLI (explicitly set) > [eval] config >
// built-in default" for every field, including the subtleties: positional args
// override [eval].paths, and the CLI '-' output sentinel maps to stdout ("").
func TestResolveEval(t *testing.T) {
	fullSec := evalSection{
		Policy:              []string{"cfg.rego"},
		Paths:               []string{"cfg/dir"},
		Format:              "json",
		Output:              "cfg.out",
		Fail:                true,
		IgnoreAutoGenerated: true,
		Workers:             7,
		ObjectDepth:         3,
	}

	t.Run("CLI values win over config when set", func(t *testing.T) {
		r := resolveEval(evalFlagInput{
			policies: []string{"cli.rego"}, policiesSet: true,
			args:   []string{"cli/dir"},
			format: "text", formatSet: true,
			output: "cli.out", outputSet: true,
			fail: false, failSet: true,
			ignoreAutoGen: false, ignoreAutoGenSet: true,
			workers: 2, workersSet: true,
			objectDepth: 1, objectDepthSet: true,
		}, fullSec)

		gt.A(t, r.policies).Equal([]string{"cli.rego"})
		gt.A(t, r.paths).Equal([]string{"cli/dir"})
		gt.V(t, r.format).Equal("text")
		gt.V(t, r.output).Equal("cli.out")
		gt.V(t, r.fail).Equal(false)
		gt.V(t, r.ignoreAutoGen).Equal(false)
		gt.V(t, r.workers).Equal(2)
		gt.V(t, r.objectDepth).Equal(1) // CLI-set object depth wins over config's 3
	})

	t.Run("config fills in when no CLI flag is set", func(t *testing.T) {
		r := resolveEval(evalFlagInput{}, fullSec) // nothing set on the CLI side

		gt.A(t, r.policies).Equal([]string{"cfg.rego"})
		gt.A(t, r.paths).Equal([]string{"cfg/dir"})
		gt.V(t, r.format).Equal("json")
		gt.V(t, r.output).Equal("cfg.out")
		gt.V(t, r.fail).Equal(true)
		gt.V(t, r.ignoreAutoGen).Equal(true)
		gt.V(t, r.workers).Equal(7)
		gt.V(t, r.objectDepth).Equal(3)
	})

	t.Run("built-in defaults when neither CLI nor config set", func(t *testing.T) {
		r := resolveEval(evalFlagInput{}, evalSection{})

		gt.A(t, r.policies).Length(0)
		gt.A(t, r.paths).Length(0)
		gt.V(t, r.format).Equal("text") // the only non-zero built-in default
		gt.V(t, r.output).Equal("")     // empty means stdout
		gt.V(t, r.fail).Equal(false)
		gt.V(t, r.ignoreAutoGen).Equal(false)
		gt.V(t, r.workers).Equal(0)
		gt.V(t, r.objectDepth).Equal(0)
	})

	t.Run("positional args override config paths", func(t *testing.T) {
		r := resolveEval(evalFlagInput{args: []string{"pos/dir"}}, fullSec)
		gt.A(t, r.paths).Equal([]string{"pos/dir"})
	})

	t.Run("no args falls back to config paths", func(t *testing.T) {
		r := resolveEval(evalFlagInput{}, fullSec)
		gt.A(t, r.paths).Equal([]string{"cfg/dir"})
	})
}

// TestResolveEvalOutputSentinel isolates the output rule: on the CLI '-' is the
// stdout sentinel and resolves to "", while the config uses a plain path with an
// empty value for stdout.
func TestResolveEvalOutputSentinel(t *testing.T) {
	t.Run("CLI '-' resolves to stdout", func(t *testing.T) {
		r := resolveEval(evalFlagInput{output: "-", outputSet: true}, evalSection{Output: "cfg.out"})
		gt.V(t, r.output).Equal("")
	})
	t.Run("CLI path wins over config", func(t *testing.T) {
		r := resolveEval(evalFlagInput{output: "cli.out", outputSet: true}, evalSection{Output: "cfg.out"})
		gt.V(t, r.output).Equal("cli.out")
	})
	t.Run("config path used when CLI unset", func(t *testing.T) {
		r := resolveEval(evalFlagInput{}, evalSection{Output: "cfg.out"})
		gt.V(t, r.output).Equal("cfg.out")
	})
	t.Run("empty config output means stdout", func(t *testing.T) {
		r := resolveEval(evalFlagInput{}, evalSection{})
		gt.V(t, r.output).Equal("")
	})
}

// TestCmdEvalConfigDriven runs eval with no CLI knobs beyond --config: policy and
// target come entirely from the [eval] section, and fail=true surfaces errEvalFail
// on the violating sample.
func TestCmdEvalConfigDriven(t *testing.T) {
	out := filepath.Join(t.TempDir(), "out.txt")
	cfg := writeConfig(t, `
[eval]
policy = ["testdata/test/no_println.rego"]
paths  = ["testdata/test/no_println_bad.go"]
output = "`+out+`"
fail   = true
`)

	cmd := cmdEval()
	err := cmd.Run(context.Background(), []string{"eval", "-c", cfg})

	gt.NotNil(t, err)
	gt.V(t, errors.Is(err, errEvalFail)).Equal(true)

	body := gt.R1(os.ReadFile(out)).NoError(t)
	gt.V(t, len(body) > 0).Equal(true)
}

// TestCmdEvalRepoRootConfig runs the repository's own shipped [eval] section
// end-to-end from the repo root: goast lints its own source with its own policy
// (.goast/). goast honors that policy, so a clean, config-driven run reports zero
// violations and exits 0 even with fail=true. This is the real dogfood — if a new
// fmt.Print* ever lands in the listed source, this test (and the CI gate) fails.
func TestCmdEvalRepoRootConfig(t *testing.T) {
	t.Chdir("../..") // move from cmd/goast to the repo root where .goast.toml lives

	out := filepath.Join(t.TempDir(), "out.txt")
	cmd := cmdEval()
	err := cmd.Run(context.Background(), []string{"eval", "-o", out}) // -c defaults to .goast.toml
	gt.NoError(t, err)

	body := string(gt.R1(os.ReadFile(out)).NoError(t))
	gt.V(t, strings.Contains(body, "Detected 0 violations")).Equal(true)
}

// TestCmdEvalDefaultConfigAbsentUsesCLIOnly proves "no config -> CLI-only": the
// working dir (cmd/goast) has no .goast.toml, so eval must run from flags alone.
func TestCmdEvalDefaultConfigAbsentUsesCLIOnly(t *testing.T) {
	out := filepath.Join(t.TempDir(), "out.txt")
	cmd := cmdEval()
	err := cmd.Run(context.Background(), []string{
		"eval",
		"-p", "testdata/test/no_println.rego",
		"-o", out,
		"testdata/test/no_println_good.go", // clean sample -> no violations
	})
	gt.NoError(t, err)
}

// TestCmdEvalMissingExplicitConfig proves an explicitly requested --config that
// does not exist is an error, not a silent CLI-only fallback.
func TestCmdEvalMissingExplicitConfig(t *testing.T) {
	missing := filepath.Join(t.TempDir(), "nope.toml")
	cmd := cmdEval()
	err := cmd.Run(context.Background(), []string{
		"eval", "-c", missing,
		"-p", "testdata/test/no_println.rego",
		"testdata/test/no_println_good.go",
	})
	gt.NotNil(t, err)
	gt.V(t, errors.Is(err, os.ErrNotExist)).Equal(true)
}

// TestCmdEvalPolicyRequired proves the requirement moved from a Required flag to
// post-resolution validation: with no --policy and no [eval].policy, eval errors.
func TestCmdEvalPolicyRequired(t *testing.T) {
	cmd := cmdEval()
	// cmd/goast has no default .goast.toml, so nothing supplies a policy.
	err := cmd.Run(context.Background(), []string{"eval", "testdata/test/no_println_good.go"})
	gt.NotNil(t, err)
}
