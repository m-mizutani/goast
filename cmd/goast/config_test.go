// TestConfigDecodePaths pins the type-safety decision: path fields are strict
// []string. An array decodes; a bare string is rejected (no string-or-array
// shim), so the config shape is unambiguous when read.
func TestConfigDecodePaths(t *testing.T) {
	t.Run("arrays decode for both sections", func(t *testing.T) {
		var cfg goastConfig
		gt.NoError(t, tomlDecode(t, `
[eval]
policy = [".goast", "extra.rego"]
paths  = ["./cmd", "./internal"]

[test]
policy = [".goast"]
[[test.cases]]
source = ["a.go", "b.go"]
expect = "pass"
`, &cfg))
		gt.A(t, cfg.Eval.Policy).Equal([]string{".goast", "extra.rego"})
		gt.A(t, cfg.Eval.Paths).Equal([]string{"./cmd", "./internal"})
		gt.A(t, cfg.Test.Policy).Equal([]string{".goast"})
		gt.A(t, cfg.Test.Cases[0].Source).Equal([]string{"a.go", "b.go"})
	})

	t.Run("bare string is rejected for [test].policy", func(t *testing.T) {
		var cfg goastConfig
		gt.NotNil(t, tomlDecode(t, `
[test]
policy = ".goast"
[[test.cases]]
source = ["a.go"]
expect = "pass"
`, &cfg))
	})

	t.Run("bare string is rejected for [eval].paths", func(t *testing.T) {
		var cfg goastConfig
		gt.NotNil(t, tomlDecode(t, `
[eval]
paths = "./..."
`, &cfg))
	})
}

// TestConfigDecodeEvalSection decodes a fully-populated [eval] table to confirm
// every field maps to the expected Go type and value.
func TestConfigDecodeEvalSection(t *testing.T) {
	var cfg goastConfig
	gt.NoError(t, tomlDecode(t, `
[eval]
policy                = [".goast"]
paths                 = ["./..."]
format                = "json"
output                = "out.json"
fail                  = true
ignore_auto_generated = true
workers               = 4
object_depth          = 2
`, &cfg))

	e := cfg.Eval
	gt.A(t, e.Policy).Equal([]string{".goast"})
	gt.A(t, e.Paths).Equal([]string{"./..."})
	gt.V(t, e.Format).Equal("json")
	gt.V(t, e.Output).Equal("out.json")
	gt.V(t, e.Fail).Equal(true)
	gt.V(t, e.IgnoreAutoGenerated).Equal(true)
	gt.V(t, e.Workers).Equal(4)
	gt.V(t, e.ObjectDepth).Equal(2)
}

// TestSectionsAreIndependent proves loadConfig does no cross-section validation:
// a file may carry [eval] only, [test] only, or both, and each subcommand
// validates only what it consumes.
func TestSectionsAreIndependent(t *testing.T) {
	t.Run("[eval] only: no [test] does not error at load, eval validates", func(t *testing.T) {
		cfg := gt.R1(loadConfig(writeConfig(t, `
[eval]
policy = [".goast"]
paths  = ["./..."]
`))).NoError(t)
		gt.A(t, cfg.Eval.Policy).Equal([]string{".goast"})
		gt.NoError(t, cfg.Eval.validate())
		// The absent [test] section has no cases; test would reject it, but eval
		// never calls testSection.validate.
		gt.NotNil(t, cfg.Test.validate())
	})

	t.Run("[test] only: no [eval] does not error at load", func(t *testing.T) {
		cfg := gt.R1(loadConfig(writeConfig(t, `
[test]
policy = [".goast"]
[[test.cases]]
source = ["a.go"]
expect = "pass"
`))).NoError(t)
		gt.NoError(t, cfg.Test.validate())
		// An empty [eval] section is valid: every field defers to the CLI default.
		gt.NoError(t, cfg.Eval.validate())
	})
}

// TestLoadConfigDefaults covers per-case default inheritance through the real
// fixture and an in-line override.
func TestLoadConfigDefaults(t *testing.T) {
	t.Run("fixture pass suite inherits the section policy", func(t *testing.T) {
		cfg := gt.R1(loadConfig("testdata/test/pass_suite.toml")).NoError(t)
		gt.A(t, cfg.Test.Cases).Length(3)
		// The third case omits policy, so it must inherit the [test] default.
		gt.A(t, cfg.Test.Cases[2].policyPaths(cfg.Test)).Equal([]string{"testdata/test/no_println.rego"})
	})

	t.Run("case policy overrides the section default", func(t *testing.T) {
		cfg := gt.R1(loadConfig(writeConfig(t, `
[test]
policy = ["default.rego"]
[[test.cases]]
source = ["a.go"]
policy = ["case.rego"]
expect = "fail"
`))).NoError(t)
		gt.A(t, cfg.Test.Cases[0].policyPaths(cfg.Test)).Equal([]string{"case.rego"})
	})
}

// TestTestSectionValidateInvalid feeds each malformed config through
// load-then-validate; every one must be rejected somewhere in that chain.
func TestTestSectionValidateInvalid(t *testing.T) {
	cases := map[string]string{
		"no cases": `
[test]
policy = ["p.rego"]
`,
		"case without source": `
[test]
policy = ["p.rego"]
[[test.cases]]
expect = "fail"
`,
		"case without any policy": `
[[test.cases]]
source = ["a.go"]
expect = "fail"
`,
		"invalid expect value": `
[test]
policy = ["p.rego"]
[[test.cases]]
source = ["a.go"]
expect = "maybe"
`,
		"no assertion": `
[test]
policy = ["p.rego"]
[[test.cases]]
source = ["a.go"]
`,
		"expect pass conflicts with count": `
[test]
policy = ["p.rego"]
[[test.cases]]
source = ["a.go"]
expect = "pass"
count = 1
`,
		"expect pass conflicts with violations": `
[test]
policy = ["p.rego"]
[[test.cases]]
source = ["a.go"]
expect = "pass"
[[test.cases.violations]]
line = 6
`,
		"expect fail conflicts with count zero": `
[test]
policy = ["p.rego"]
[[test.cases]]
source = ["a.go"]
expect = "fail"
count = 0
`,
		"count zero conflicts with violations": `
[test]
policy = ["p.rego"]
[[test.cases]]
source = ["a.go"]
count = 0
[[test.cases.violations]]
line = 6
`,
		"negative count": `
[test]
policy = ["p.rego"]
[[test.cases]]
source = ["a.go"]
count = -1
`,
		"empty violation entry": `
[test]
policy = ["p.rego"]
[[test.cases]]
source = ["a.go"]
[[test.cases.violations]]
`,
		"toml syntax error": `
[test
policy = ["p.rego"]
`,
	}

	for name, content := range cases {
		t.Run(name, func(t *testing.T) {
			cfg, err := loadConfig(writeConfig(t, content))
			if err == nil {
				err = cfg.Test.validate()
			}
			gt.NotNil(t, err)
		})
	}
}

// TestEvalSectionValidate covers the standalone [eval] checks: only fields that
// carry a value are validated; empty fields defer to CLI defaults.
func TestEvalSectionValidate(t *testing.T) {
	t.Run("empty section is valid", func(t *testing.T) {
		gt.NoError(t, evalSection{}.validate())
	})
	t.Run("fully populated valid section", func(t *testing.T) {
		gt.NoError(t, evalSection{Format: "json", Workers: 8, ObjectDepth: 2}.validate())
	})
	t.Run("unsupported format is rejected", func(t *testing.T) {
		gt.NotNil(t, evalSection{Format: "yaml"}.validate())
	})
	t.Run("negative workers is rejected", func(t *testing.T) {
		gt.NotNil(t, evalSection{Workers: -1}.validate())
	})
	t.Run("negative object_depth is rejected", func(t *testing.T) {
		gt.NotNil(t, evalSection{ObjectDepth: -1}.validate())
	})
}

// --- helpers ---

func writeConfig(t *testing.T, content string) string {
	t.Helper()
	path := filepath.Join(t.TempDir(), "cfg.toml")
	gt.NoError(t, os.WriteFile(path, []byte(content), 0600))
	return path
}

func tomlDecode(t *testing.T, content string, v any) error {
	t.Helper()
	return toml.Unmarshal([]byte(content), v)
}
