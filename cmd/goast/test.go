// errTestFail marks "the suite ran and one or more cases failed their
// assertions". It is deliberately distinct from load/parse/compile errors so a
// caller (and the tests) can tell an assertion failure apart from a broken test
// setup via errors.Is — the CLI turns both into a non-zero exit, but they mean
// different things.
var errTestFail = errors.New("policy test failures")

// pathList accepts either a bare string or an array of strings in TOML, so both
// `policy = ".goast"` and `policy = [".goast", "extra.rego"]` decode into the
// same shape. Without this, the config would force every single-path field to be
// written as a one-element array.
type pathList []string

func (p *pathList) UnmarshalTOML(v any) error {
	switch val := v.(type) {
	case string:
		*p = pathList{val}
	case []string:
		*p = append(pathList(nil), val...)
	case []any:
		out := make(pathList, 0, len(val))
		for _, e := range val {
			s, ok := e.(string)
			if !ok {
				return goerr.New("path list must contain only strings", goerr.V("element", e))
			}
			out = append(out, s)
		}
		*p = out
	default:
		return goerr.New("expected a string or an array of strings", goerr.V("value", v))
	}
	return nil
}

// testConfig is the root of a .goast.toml file.
type testConfig struct {
	Test testSection `toml:"test"`
}

// testSection carries the [test] table: defaults shared by every case plus the
// list of cases themselves.
type testSection struct {
	Policy              pathList    `toml:"policy"`
	ObjectDepth         int         `toml:"object_depth"`
	IgnoreAutoGenerated bool        `toml:"ignore_auto_generated"`
	Cases               []*testCase `toml:"cases"`
}

// testCase is one [[test.cases]] entry: which policy to compile, which Go source
// to run it over, and what result to expect. count / violations are optional
// refinements on top of expect.
type testCase struct {
	Name                string               `toml:"name"`
	Policy              pathList             `toml:"policy"`
	Source              pathList             `toml:"source"`
	Expect              string               `toml:"expect"`
	Count               *int                 `toml:"count"`
	Violations          []*expectedViolation `toml:"violations"`
	ObjectDepth         *int                 `toml:"object_depth"`
	IgnoreAutoGenerated *bool                `toml:"ignore_auto_generated"`
}

// expectedViolation asserts that at least one reported violation matches every
// field that is set here. Each field is independently optional; an entry with no
// fields at all is rejected at load time because it would match anything.
type expectedViolation struct {
	Line     *int   `toml:"line"`
	Column   *int   `toml:"column"`
	Message  string `toml:"message"`
	Severity string `toml:"severity"`
}

// loadTestConfig reads, parses, and validates a .goast.toml file. Validation
// happens here (not at run time) so a contradictory config is rejected before
// any policy is compiled.
func loadTestConfig(path string) (*testConfig, error) {
	raw, err := os.ReadFile(filepath.Clean(path)) // #nosec G304 -- config path is operator-supplied, reading it is the command's purpose
	if err != nil {
		return nil, goerr.Wrap(err, "failed to read test config", goerr.V("path", path))
	}

	var cfg testConfig
	if err := toml.Unmarshal(raw, &cfg); err != nil {
		return nil, goerr.Wrap(err, "failed to parse test config", goerr.V("path", path))
	}

	if err := cfg.validate(); err != nil {
		return nil, goerr.Wrap(err, "invalid test config", goerr.V("path", path))
	}

	return &cfg, nil
}

func (cfg *testConfig) validate() error {
	if len(cfg.Test.Cases) == 0 {
		return goerr.New("no test cases defined; add at least one [[test.cases]]")
	}
	for i, c := range cfg.Test.Cases {
		if err := c.validate(cfg.Test); err != nil {
			return goerr.Wrap(err, "invalid test case", goerr.V("index", i), goerr.V("name", c.Name))
		}
	}
	return nil
}

func (c *testCase) validate(section testSection) error {
	if len(c.Source) == 0 {
		return goerr.New("case has no source")
	}
	if len(c.policyPaths(section)) == 0 {
		return goerr.New("case has no policy; set case.policy or [test].policy")
	}

	expect := strings.ToLower(c.Expect)
	if expect != "" && expect != "pass" && expect != "fail" {
		return goerr.New(`expect must be "pass" or "fail"`, goerr.V("expect", c.Expect))
	}

	// A case needs at least one assertion, otherwise it asserts nothing.
	if expect == "" && c.Count == nil && len(c.Violations) == 0 {
		return goerr.New("case has no assertion; set expect, count, or violations")
	}

	if c.Count != nil && *c.Count < 0 {
		return goerr.New("count must be >= 0", goerr.V("count", *c.Count))
	}

	// Contradictions: reject a config that can never be satisfied rather than
	// letting it fail confusingly at run time.
	if expect == "pass" {
		if c.Count != nil && *c.Count != 0 {
			return goerr.New("expect=pass conflicts with count > 0", goerr.V("count", *c.Count))
		}
		if len(c.Violations) > 0 {
			return goerr.New("expect=pass conflicts with declared violations")
		}
	}
	if expect == "fail" && c.Count != nil && *c.Count == 0 {
		return goerr.New("expect=fail conflicts with count == 0")
	}
	// count == 0 means "no violations", which cannot coexist with declared ones,
	// regardless of whether expect was written out.
	if c.Count != nil && *c.Count == 0 && len(c.Violations) > 0 {
		return goerr.New("count=0 conflicts with declared violations")
	}

	for j, v := range c.Violations {
		if v.Line == nil && v.Column == nil && v.Message == "" && v.Severity == "" {
			return goerr.New("violation entry must set at least one of line/column/message/severity", goerr.V("violation_index", j))
		}
	}

	return nil
}

// policyPaths returns the case policy if set, otherwise the section default.
func (c *testCase) policyPaths(section testSection) []string {
	if len(c.Policy) > 0 {
		return c.Policy
	}
	return section.Policy
}

func (c *testCase) objectDepth(section testSection) int {
	if c.ObjectDepth != nil {
		return *c.ObjectDepth
	}
	return section.ObjectDepth
}

func (c *testCase) ignoreAutoGen(section testSection) bool {
	if c.IgnoreAutoGenerated != nil {
		return *c.IgnoreAutoGenerated
	}
	return section.IgnoreAutoGenerated
}

func (c *testCase) displayName(index int) string {
	if c.Name != "" {
		return c.Name
	}
	if len(c.Source) > 0 {
		return c.Source[0]
	}
	return fmt.Sprintf("case #%d", index+1)
}

// expectsFail reports whether the case expects at least one violation. It is
// only meaningful after validate has accepted the case: with expect omitted it
// derives the expectation from count / violations, which validate has already
// proven internally consistent.
func (c *testCase) expectsFail() bool {
	switch strings.ToLower(c.Expect) {
	case "fail":
		return true
	case "pass":
		return false
	}
	if len(c.Violations) > 0 {
		return true
	}
	if c.Count != nil {
		return *c.Count > 0
	}
	return false
}

// checkCase compares the violations produced for a case against its declared
// expectations and returns a reason for every mismatch. An empty slice means the
// case passed. Every mismatch is collected (not short-circuited) so one run
// reports every way the case diverged.
func checkCase(c *testCase, fails []*goast.Fail) []string {
	var reasons []string

	switch expectFail := c.expectsFail(); {
	case expectFail && len(fails) == 0:
		reasons = append(reasons, "expected at least one violation, but got none")
	case !expectFail && len(fails) > 0:
		reasons = append(reasons, fmt.Sprintf("expected no violations, but got %d: %s", len(fails), formatFails(fails)))
	}

	if c.Count != nil && len(fails) != *c.Count {
		reasons = append(reasons, fmt.Sprintf("expected exactly %d violation(s), but got %d: %s", *c.Count, len(fails), formatFails(fails)))
	}

	for _, want := range c.Violations {
		if !matchesAnyViolation(want, fails) {
			reasons = append(reasons, fmt.Sprintf("expected a violation matching %s, but got: %s", want.describe(), formatFails(fails)))
		}
	}

	return reasons
}

// matchesAnyViolation reports whether any reported violation satisfies every
// field set on want. Unset fields are wildcards, so an entry with only line set
// matches on line alone.
func matchesAnyViolation(want *expectedViolation, fails []*goast.Fail) bool {
	for _, f := range fails {
		if want.Line != nil && f.Line != *want.Line {
			continue
		}
		if want.Column != nil && f.Column != *want.Column {
			continue
		}
		if want.Message != "" && !strings.Contains(f.Msg, want.Message) {
			continue
		}
		if want.Severity != "" && !strings.EqualFold(f.Sev, want.Severity) {
			continue
		}
		return true
	}
	return false
}

func (v *expectedViolation) describe() string {
	var parts []string
	if v.Line != nil {
		parts = append(parts, fmt.Sprintf("line=%d", *v.Line))
	}
	if v.Column != nil {
		parts = append(parts, fmt.Sprintf("column=%d", *v.Column))
	}
	if v.Message != "" {
		parts = append(parts, fmt.Sprintf("message~=%q", v.Message))
	}
	if v.Severity != "" {
		parts = append(parts, fmt.Sprintf("severity=%q", v.Severity))
	}
	return "{" + strings.Join(parts, ", ") + "}"
}

func formatFails(fails []*goast.Fail) string {
	if len(fails) == 0 {
		return "[]"
	}
	parts := make([]string, 0, len(fails))
	for _, f := range fails {
		parts = append(parts, fmt.Sprintf("[%s:%d:%d] %q", f.Path, f.Line, f.Column, f.Msg))
	}
	return "[" + strings.Join(parts, ", ") + "]"
}

// engineCache compiles each distinct policy set once and reuses it across cases.
// A goast policy suite typically points many cases at the same .goast directory,
// so compiling per case would repeat the (relatively expensive) Rego compile for
// no reason.
type engineCache struct {
	engines map[string]*goast.PolicyEngine
}

func newEngineCache() *engineCache {
	return &engineCache{engines: map[string]*goast.PolicyEngine{}}
}

func (ec *engineCache) get(paths []string) (*goast.PolicyEngine, error) {
	// Key on the sorted paths: NewPolicyEngine dedups by absolute path and is
	// order-independent, so two cases naming the same policies in a different
	// order should share one compiled engine.
	key := make([]string, len(paths))
	copy(key, paths)
	sort.Strings(key)
	cacheKey := strings.Join(key, "\x00")

	if e, ok := ec.engines[cacheKey]; ok {
		return e, nil
	}
	e, err := goast.NewPolicyEngine(paths...)
	if err != nil {
		return nil, err
	}
	ec.engines[cacheKey] = e
	return e, nil
}

// runCase compiles the case's policy, collects its source .go files, and
// evaluates them, returning the findings in deterministic walk order.
func runCase(ec *engineCache, section testSection, c *testCase) ([]*goast.Fail, error) {
	paths := c.policyPaths(section)
	engine, err := ec.get(paths)
	if err != nil {
		return nil, goerr.Wrap(err, "failed to load policy", goerr.V("policy", paths))
	}

	opts := []goast.Option{goast.WithPolicyEngine(engine)}
	if depth := c.objectDepth(section); depth > 0 {
		opts = append(opts, goast.WithInspectOptions(goast.WithObjectDepth(depth)))
	}
	if c.ignoreAutoGen(section) {
		opts = append(opts, goast.WithIgnoreAutoGen())
	}
	g := goast.New(opts...)

	files, err := listGoFiles(c.Source)
	if err != nil {
		return nil, err
	}

	fails, err := evalFilesParallel(files, 0, g.Eval)
	if err != nil {
		return nil, err
	}
	return fails, nil
}

type caseOutcome struct {
	name       string
	violations int
	reasons    []string // empty means the case passed
}

// runTests runs every case in order and writes a per-case report plus a summary
// to w. A broken setup (unreadable/uncompilable policy, unparseable fixture) is
// returned as an error and aborts the run; assertion failures do not abort but
// make the final return errTestFail.
func runTests(cfg *testConfig, w io.Writer) error {
	ec := newEngineCache()
	outcomes := make([]caseOutcome, 0, len(cfg.Test.Cases))

	for i, c := range cfg.Test.Cases {
		name := c.displayName(i)
		fails, err := runCase(ec, cfg.Test, c)
		if err != nil {
			return goerr.Wrap(err, "failed to run test case", goerr.V("case", name))
		}
		outcomes = append(outcomes, caseOutcome{
			name:       name,
			violations: len(fails),
			reasons:    checkCase(c, fails),
		})
	}

	return reportOutcomes(w, outcomes)
}

func reportOutcomes(w io.Writer, outcomes []caseOutcome) error {
	passed := 0
	for _, o := range outcomes {
		if len(o.reasons) == 0 {
			passed++
			printStatus(w, true, o.name)
			fmt.Fprintf(w, "  (%s)\n", pluralViolations(o.violations))
			continue
		}
		printStatus(w, false, o.name)
		fmt.Fprintln(w)
		for _, r := range o.reasons {
			fmt.Fprintf(w, "        %s\n", r)
		}
	}

	failed := len(outcomes) - passed
	fmt.Fprintf(w, "\n%d cases: %d passed, %d failed\n", len(outcomes), passed, failed)

	if failed > 0 {
		return goerr.Wrap(errTestFail, "policy tests failed", goerr.V("failed", failed), goerr.V("total", len(outcomes)))
	}
	return nil
}

func pluralViolations(n int) string {
	if n == 1 {
		return "1 violation"
	}
	return fmt.Sprintf("%d violations", n)
}

// printStatus writes the "ok"/"FAIL" label, colored only when writing to a real
// terminal (stdout) so piped/captured output stays plain — the same rule the
// eval text output follows.
func printStatus(w io.Writer, ok bool, name string) {
	label := "ok  "
	col := color.New(color.FgGreen)
	if !ok {
		label = "FAIL"
		col = color.New(color.FgRed)
	}

	// Colorize only for a real terminal (stdout); Sprint returns a plain string
	// so there is no write error to drop, unlike the color Fprint helpers.
	if w == os.Stdout {
		label = col.Sprint(label)
	}
	fmt.Fprintf(w, "%s  %s", label, name)
}

func cmdTest() *cli.Command {
	var config string

	return &cli.Command{
		Name:    "test",
		Usage:   "run declarative policy tests defined in a TOML config",
		Aliases: []string{"t"},
		Flags: []cli.Flag{
			&cli.StringFlag{
				Name:        "config",
				Aliases:     []string{"c"},
				Sources:     cli.EnvVars("GOAST_TEST_CONFIG"),
				Destination: &config,
				Value:       ".goast.toml",
				Usage:       "Path to the test config TOML file",
			},
		},
		Action: func(_ context.Context, _ *cli.Command) error {
			cfg, err := loadTestConfig(config)
			if err != nil {
				return err
			}
			return runTests(cfg, os.Stdout)
		},
	}
}
