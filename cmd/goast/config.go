package main

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/BurntSushi/toml"
	"github.com/m-mizutani/goerr/v2"
)

// goastConfig is the root of a .goast.toml file. Both sections are optional: a
// file may declare [eval] only, [test] only, or both. Cross-section validation
// is deliberately NOT performed at load time (see loadConfig) — each subcommand
// validates only the section it consumes, so an eval run does not require a
// [test] table to exist and vice versa.
type goastConfig struct {
	Eval evalSection `toml:"eval"`
	Test testSection `toml:"test"`
}

// evalSection carries [eval]: defaults for `goast eval` used when the matching
// CLI flag is not set. Every field is optional; a zero value means "unset" and
// falls back to the CLI flag's built-in default. Paths are []string (not a
// string-or-array shim) so the config is unambiguous to read and review.
type evalSection struct {
	Policy              []string `toml:"policy"`
	Paths               []string `toml:"paths"`
	Format              string   `toml:"format"`
	Output              string   `toml:"output"`
	Fail                bool     `toml:"fail"`
	IgnoreAutoGenerated bool     `toml:"ignore_auto_generated"`
	Workers             int      `toml:"workers"`
	ObjectDepth         int      `toml:"object_depth"`
}

// testSection carries the [test] table: defaults shared by every case plus the
// list of cases themselves.
type testSection struct {
	Policy              []string    `toml:"policy"`
	ObjectDepth         int         `toml:"object_depth"`
	IgnoreAutoGenerated bool        `toml:"ignore_auto_generated"`
	Cases               []*testCase `toml:"cases"`
}

// testCase is one [[test.cases]] entry: which policy to compile, which Go source
// to run it over, and what result to expect. count / violations are optional
// refinements on top of expect.
type testCase struct {
	Name                string               `toml:"name"`
	Policy              []string             `toml:"policy"`
	Source              []string             `toml:"source"`
	Expect              string               `toml:"expect"`
	Count               *int                 `toml:"count"`
	Violations          []*expectedViolation `toml:"violations"`
	ObjectDepth         *int                 `toml:"object_depth"`
	IgnoreAutoGenerated *bool                `toml:"ignore_auto_generated"`
}

// expectedViolation asserts that at least one reported violation matches every
// field that is set here. Each field is independently optional; an entry with no
// fields at all is rejected at load time because it would match anything.
type expectedViolation struct {
	Line     *int   `toml:"line"`
	Column   *int   `toml:"column"`
	Message  string `toml:"message"`
	Severity string `toml:"severity"`
}

// loadConfig reads and parses a .goast.toml file. It does NOT validate any
// section: validation is the consuming subcommand's job (testSection.validate /
// evalSection.validate), because one file may carry [eval] only, [test] only, or
// both. A missing file surfaces as an error wrapping os.ErrNotExist, so callers
// can tell "no config" apart from "broken config" with errors.Is.
func loadConfig(path string) (*goastConfig, error) {
	raw, err := os.ReadFile(filepath.Clean(path)) // #nosec G304 -- config path is operator-supplied, reading it is the command's purpose
	if err != nil {
		return nil, goerr.Wrap(err, "failed to read config", goerr.V("path", path))
	}

	var cfg goastConfig
	if err := toml.Unmarshal(raw, &cfg); err != nil {
		return nil, goerr.Wrap(err, "failed to parse config", goerr.V("path", path))
	}

	return &cfg, nil
}

// validate checks the [eval] section in isolation. Only fields that carry a
// value are checked; an empty field defers to the CLI flag's default and is
// resolved later, so it is not an error here.
func (e evalSection) validate() error {
	if e.Format != "" {
		if _, ok := toOutputFormat(e.Format); !ok {
			return goerr.New("unsupported output format", goerr.V("format", e.Format))
		}
	}
	if e.Workers < 0 {
		return goerr.New("workers must be >= 0", goerr.V("workers", e.Workers))
	}
	if e.ObjectDepth < 0 {
		return goerr.New("object_depth must be >= 0", goerr.V("object_depth", e.ObjectDepth))
	}
	return nil
}

// validate checks the [test] section. Validation happens here (not at run time)
// so a contradictory config is rejected before any policy is compiled.
func (s testSection) validate() error {
	if len(s.Cases) == 0 {
		return goerr.New("no test cases defined; add at least one [[test.cases]]")
	}
	for i, c := range s.Cases {
		if err := c.validate(s); err != nil {
			return goerr.Wrap(err, "invalid test case", goerr.V("index", i), goerr.V("name", c.Name))
		}
	}
	return nil
}

func (c *testCase) validate(section testSection) error {
	if len(c.Source) == 0 {
		return goerr.New("case has no source")
	}
	if len(c.policyPaths(section)) == 0 {
		return goerr.New("case has no policy; set case.policy or [test].policy")
	}

	expect := strings.ToLower(c.Expect)
	if expect != "" && expect != "pass" && expect != "fail" {
		return goerr.New(`expect must be "pass" or "fail"`, goerr.V("expect", c.Expect))
	}

	// A case needs at least one assertion, otherwise it asserts nothing.
	if expect == "" && c.Count == nil && len(c.Violations) == 0 {
		return goerr.New("case has no assertion; set expect, count, or violations")
	}

	if c.Count != nil && *c.Count < 0 {
		return goerr.New("count must be >= 0", goerr.V("count", *c.Count))
	}

	// Contradictions: reject a config that can never be satisfied rather than
	// letting it fail confusingly at run time.
	if expect == "pass" {
		if c.Count != nil && *c.Count != 0 {
			return goerr.New("expect=pass conflicts with count > 0", goerr.V("count", *c.Count))
		}
		if len(c.Violations) > 0 {
			return goerr.New("expect=pass conflicts with declared violations")
		}
	}
	if expect == "fail" && c.Count != nil && *c.Count == 0 {
		return goerr.New("expect=fail conflicts with count == 0")
	}
	// count == 0 means "no violations", which cannot coexist with declared ones,
	// regardless of whether expect was written out.
	if c.Count != nil && *c.Count == 0 && len(c.Violations) > 0 {
		return goerr.New("count=0 conflicts with declared violations")
	}

	for j, v := range c.Violations {
		if v.Line == nil && v.Column == nil && v.Message == "" && v.Severity == "" {
			return goerr.New("violation entry must set at least one of line/column/message/severity", goerr.V("violation_index", j))
		}
	}

	return nil
}

// policyPaths returns the case policy if set, otherwise the section default.
func (c *testCase) policyPaths(section testSection) []string {
	if len(c.Policy) > 0 {
		return c.Policy
	}
	return section.Policy
}

func (c *testCase) objectDepth(section testSection) int {
	if c.ObjectDepth != nil {
		return *c.ObjectDepth
	}
	return section.ObjectDepth
}

func (c *testCase) ignoreAutoGen(section testSection) bool {
	if c.IgnoreAutoGenerated != nil {
		return *c.IgnoreAutoGenerated
	}
	return section.IgnoreAutoGenerated
}

func (c *testCase) displayName(index int) string {
	if c.Name != "" {
		return c.Name
	}
	if len(c.Source) > 0 {
		return c.Source[0]
	}
	return fmt.Sprintf("case #%d", index+1)
}

// expectsFail reports whether the case expects at least one violation. It is
// only meaningful after validate has accepted the case: with expect omitted it
// derives the expectation from count / violations, which validate has already
// proven internally consistent.
func (c *testCase) expectsFail() bool {
	switch strings.ToLower(c.Expect) {
	case "fail":
		return true
	case "pass":
		return false
	}
	if len(c.Violations) > 0 {
		return true
	}
	if c.Count != nil {
		return *c.Count > 0
	}
	return false
}
