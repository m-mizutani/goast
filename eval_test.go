// stubEngine emulates the policy engine by routing the query input through fn and
// JSON-encoding the result into output, mirroring how the engine decodes Rego output.
type stubEngine struct {
	fn func(in any) (any, error)
}

func (s *stubEngine) Query(_ context.Context, _ string, input, output any) error {
	result, err := s.fn(input)
	if err != nil {
		return err
	}
	if result == nil {
		return nil
	}
	raw, err := json.Marshal(result)
	if err != nil {
		return err
	}
	return json.Unmarshal(raw, output)
}

const evalExampleCode = `package main

func Add(a, b int) int {
	return a + b
}
`

func TestEval(t *testing.T) {
	code := strings.NewReader(evalExampleCode)

	mock := &stubEngine{fn: func(in any) (any, error) {
		node := gt.Cast[*goast.Node](t, in)
		if node.Kind != "File" {
			return nil, nil
		}

		src := gt.Cast[*ast.File](t, node.Node)
		gt.A(t, src.Decls).Required().Length(1)
		f := gt.Cast[*ast.FuncDecl](t, src.Decls[0])
		gt.V(t, f.Name.Name).Equal("Add")

		// The engine now queries data.goast.fail, whose value is the fail set
		// itself: a JSON array of {msg,pos,sev}, not an object wrapping it.
		return []*goast.FailCase{
			{
				Msg: "eval_test",
				Pos: 15,
			},
		}, nil
	}}

	g := goast.New(
		goast.WithPolicyEngine(mock),
	)

	fails := gt.R1(g.Eval("test.go", code)).NoError(t)

	gt.A(t, fails).Length(1)
	gt.V(t, fails[0].Line).Equal(3)
	gt.V(t, fails[0].Msg).Equal("eval_test")
}

// TestEvalWithRealPolicy exercises the real OPA evaluation path (not the stub) to
// guard the Rego v1 enforcement: PolicyEngine compiles policies as ast.RegoV1, so
// the v1-syntax policies under policy/ must compile and match without needing an
// `import rego.v1` line.
func TestEvalWithRealPolicy(t *testing.T) {
	const code = `package main

import "fmt"

func hello() {
	fmt.Println("hello")
}
`
	engine := gt.R1(goast.NewPolicyEngine("policy/do_not_use_println.rego")).NoError(t)

	g := goast.New(goast.WithPolicyEngine(engine))

	fails := gt.R1(g.Eval("test.go", strings.NewReader(code))).NoError(t)
	gt.A(t, fails).Required().Length(1)
	gt.V(t, fails[0].Msg).Equal("do not use fmt.Println")
}

// TestEvalGolden pins the full Eval output (every field of every Fail, in walk
// order) over a corpus designed to cover the behaviors that performance work
// must not change: multiple policies contributing to the fail set, helper
// rules, constant sets, metadata filters, same-package test rules
// (no_fmt_print_test.rego) and auto-generated file handling.
//
// The golden file was generated by the pre-optimization implementation. Any
// behavioral drift — matching, positions, messages, severities, ordering —
// fails this test. Regenerate deliberately with GOAST_UPDATE_GOLDEN=1.
// evalCorpus runs g over every .go file under testdata/eval/src in walk order
// and returns the concatenated findings. Used by the golden and equivalence
// tests as the common "run the whole corpus" primitive.
func evalCorpus(t *testing.T, engine *goast.PolicyEngine, options ...goast.Option) []*goast.Fail {
	t.Helper()
	g := goast.New(append([]goast.Option{goast.WithPolicyEngine(engine)}, options...)...)

	fails := []*goast.Fail{}
	err := filepath.WalkDir("testdata/eval/src", func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() || filepath.Ext(path) != ".go" {
			return nil
		}
		fd, err := os.Open(path)
		if err != nil {
			return err
		}
		defer func() {
			if cerr := fd.Close(); cerr != nil {
				t.Errorf("close %s: %v", path, cerr)
			}
		}()

		resp, err := g.Eval(path, fd)
		if err != nil {
			return err
		}
		fails = append(fails, resp...)
		return nil
	})
	gt.NoError(t, err)
	return fails
}

func TestEvalGolden(t *testing.T) {
	const goldenPath = "testdata/eval/golden.json"

	engine := gt.R1(goast.NewPolicyEngine("testdata/eval/policy")).NoError(t)

	got := map[string][]*goast.Fail{
		"default":         evalCorpus(t, engine),
		"ignore_auto_gen": evalCorpus(t, engine, goast.WithIgnoreAutoGen()),
	}

	if os.Getenv("GOAST_UPDATE_GOLDEN") != "" {
		raw := gt.R1(json.MarshalIndent(got, "", "  ")).NoError(t)
		gt.NoError(t, os.WriteFile(goldenPath, append(raw, '\n'), 0600))
	}

	raw := gt.R1(os.ReadFile(goldenPath)).NoError(t)
	var want map[string][]*goast.Fail
	gt.NoError(t, json.Unmarshal(raw, &want))

	// The corpus must actually detect violations; an empty golden would make
	// this test vacuous.
	gt.A(t, want["default"]).Longer(0)

	gt.V(t, got).Equal(want)
}

// Eval has two parse paths: the default skips object resolution and hands raw
// nodes to the policy, while WithObjectDepth(>0) keeps the classic resolve +
// deep-clone path so *ast.Object survives. Detection must not depend on which
// path runs, since policies key off syntax, not the object graph.
func TestEvalObjectDepthPreservesDetection(t *testing.T) {
	engine := gt.R1(goast.NewPolicyEngine("testdata/eval/policy")).NoError(t)

	base := evalCorpus(t, engine)
	deep := evalCorpus(t, engine, goast.WithInspectOptions(goast.WithObjectDepth(3)))

	gt.A(t, base).Longer(0)
	gt.V(t, deep).Equal(base)
}

// The two parse paths must genuinely differ in what they expose: the default
// path leaves *ast.Ident.Obj nil (object resolution skipped), while
// WithObjectDepth retains it. This guards the escape hatch — a policy that
// needs the object graph can still get it.
func TestEvalObjectDepthControlsObjectGraph(t *testing.T) {
	const code = `package main

func f() {
	x := 1
	_ = x
}
`
	anyIdentHasObj := func(opts ...goast.Option) bool {
		found := false
		mock := &stubEngine{fn: func(in any) (any, error) {
			node := gt.Cast[*goast.Node](t, in)
			ast.Inspect(node.Node, func(n ast.Node) bool {
				if id, ok := n.(*ast.Ident); ok && id.Obj != nil {
					found = true
				}
				return true
			})
			return nil, nil
		}}
		g := goast.New(append([]goast.Option{goast.WithPolicyEngine(mock)}, opts...)...)
		gt.R1(g.Eval("test.go", strings.NewReader(code))).NoError(t)
		return found
	}

	// Default: object resolution skipped, so no Ident carries an Obj.
	gt.V(t, anyIdentHasObj()).Equal(false)

	// WithObjectDepth: classic path resolves and retains the object graph.
	gt.V(t, anyIdentHasObj(goast.WithInspectOptions(goast.WithObjectDepth(2)))).Equal(true)
}

func TestIgnoreAutoGeneratedFile(t *testing.T) {
	const code = `// Code generated by yo. DO NOT EDIT.
// Package model contains the types.
package main

func Add(a, b int) int {
	return a + b
}
`
	mock := &stubEngine{fn: func(in any) (any, error) {
		return []*goast.FailCase{
			{
				Msg: "always fail",
				Pos: 15,
			},
		}, nil
	}}

	t.Run("with ignore option", func(t *testing.T) {
		g := goast.New(
			goast.WithPolicyEngine(mock),
			goast.WithIgnoreAutoGen(),
		)

		fails := gt.R1(
			g.Eval("test.go", strings.NewReader(code)),
		).NoError(t)
		gt.A(t, fails).Length(0)
	})

	t.Run("without ignore option", func(t *testing.T) {
		g := goast.New(
			goast.WithPolicyEngine(mock),
		)

		fails := gt.R1(g.Eval("test.go", strings.NewReader(code))).NoError(t)
		gt.A(t, fails).Longer(0)
	})
}
